const { test } = require('node:test')
const assert = require('node:assert/strict')
const { once } = require('node:events')
const { createApp } = require('../../src/app')
const { getPool, closePool } = require('../../src/db/pool')
const { env, assertProductionConfig } = require('../../src/config/env')
const { hashPassword } = require('../../src/lib/passwords')
const { createMiniProgram } = require('../helpers/miniprogram')

test('real MySQL and HTTP: complete campus workflows and permission boundaries', async t => {
  assert.equal(env.nodeEnv, 'test')
  assert.match(env.database.name, /_test$/)
  assertProductionConfig()
  const pool = getPool()
  const connection = await pool.getConnection()
  try {
    await connection.query('SET FOREIGN_KEY_CHECKS = 0')
    for (const table of ['admin_action_logs', 'reports', 'comments', 'posts', 'task_events', 'task_messages', 'tasks', 'users', 'admin_users']) await connection.query(`TRUNCATE TABLE ${table}`)
  } finally { await connection.query('SET FOREIGN_KEY_CHECKS = 1'); connection.release() }
  await pool.execute('INSERT INTO admin_users (username, password_hash) VALUES (?, ?)', ['test-admin', await hashPassword('long-test-password')])
  const server = createApp().listen(0, '127.0.0.1')
  await once(server, 'listening')
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await closePool() })
  const base = `http://127.0.0.1:${server.address().port}/api/v1`
  async function call(path, token, method = 'GET', body) {
    const res = await fetch(base + path, { method, headers: { 'content-type': 'application/json', ...(token ? { authorization: `Bearer ${token}` } : {}) }, body: body === undefined ? undefined : JSON.stringify(body) })
    return { httpStatus: res.status, ...(await res.json()) }
  }
  async function login(name) { const res = await call('/auth/wechat-login', null, 'POST', { code: `demo:${name}` }); assert.equal(res.httpStatus, 200); return res }
  const owner = await login('owner'), helper = await login('helper'), stranger = await login('stranger')
  const admin = await call('/auth/admin-login', null, 'POST', { username: 'test-admin', password: 'long-test-password' })
  assert.equal(admin.httpStatus, 200)
  const taskInput = { title: '图书馆代取预约书', description: '请代取一本预约书', category: 'ERRAND', rewardAmount: '3.50', publicArea: '图书馆', exactLocation: '一楼服务台 A 号柜' }
  let taskId, postId

  await t.test('authentication and administrator routes are isolated', async () => {
    assert.equal((await call('/tasks')).httpStatus, 401)
    assert.equal((await call('/admin/reports', owner.token)).httpStatus, 401)
    assert.equal((await call('/tasks', admin.token)).httpStatus, 401)
    assert.equal((await call('/admin/reports', admin.token)).httpStatus, 200)
    assert.equal((await call('/tasks/not-an-id', owner.token)).httpStatus, 400)
  })

  await t.test('create validates money/deadlines; private location is omitted for others', async () => {
    for (const rewardAmount of ['3.001', true, -5]) assert.equal((await call('/tasks', owner.token, 'POST', { ...taskInput, rewardAmount })).httpStatus, 400)
    assert.equal((await call('/tasks', owner.token, 'POST', { ...taskInput, deadlineAt: '2000-01-01T00:00:00Z' })).httpStatus, 400)
    const created = await call('/tasks', owner.token, 'POST', taskInput)
    assert.equal(created.httpStatus, 201); taskId = created.task.id
    assert.ok(Math.abs(Date.now() - new Date(created.task.createdAt).getTime()) < 10000, 'database timestamps must represent UTC instants')
    assert.equal(created.task.exactLocation, taskInput.exactLocation)
    const outsider = await call(`/tasks/${taskId}`, stranger.token)
    assert.equal(outsider.task.exactLocation, null)
    assert.equal((await call('/tasks', stranger.token)).tasks[0].exactLocation, null)
    assert.equal((await call(`/tasks/${taskId}/messages`, stranger.token)).httpStatus, 403)
  })

  await t.test('concurrent accepts produce exactly one winner with no leaked assignment', async () => {
    assert.equal((await call(`/tasks/${taskId}/accept`, owner.token, 'POST', {})).httpStatus, 400)
    const attempts = await Promise.all(Array.from({ length: 12 }, () => call(`/tasks/${taskId}/accept`, helper.token, 'POST', {})))
    assert.equal(attempts.filter(result => result.httpStatus === 200).length, 1)
    assert.equal(attempts.filter(result => result.httpStatus === 409).length, 11)
    assert.equal((await call(`/tasks/${taskId}`, helper.token)).task.exactLocation, taskInput.exactLocation)
    assert.equal((await call(`/tasks/${taskId}`, stranger.token)).task.exactLocation, null)
    const [events] = await pool.execute("SELECT id FROM task_events WHERE task_id = ? AND event_type = 'ACCEPTED'", [taskId])
    assert.equal(events.length, 1)
  })

  await t.test('only participants can message; only owner can confirm completion', async () => {
    assert.equal((await call(`/tasks/${taskId}/messages`, stranger.token, 'POST', { content: '越权留言' })).httpStatus, 403)
    assert.equal((await call(`/tasks/${taskId}/messages`, helper.token, 'POST', { content: '已经取到书了' })).httpStatus, 201)
    assert.equal((await call(`/tasks/${taskId}/messages`, owner.token)).messages.length, 1)
    assert.equal((await call(`/tasks/${taskId}/complete`, owner.token, 'POST', {})).httpStatus, 403)
    assert.equal((await call(`/tasks/${taskId}/complete`, helper.token, 'POST', {})).task.status, 'COMPLETION_PENDING')
    assert.equal((await call(`/tasks/${taskId}/confirm`, helper.token, 'POST', {})).httpStatus, 403)
    assert.equal((await call(`/tasks/${taskId}/confirm`, owner.token, 'POST', {})).task.status, 'COMPLETED')
    assert.equal((await call(`/tasks/${taskId}/messages`, owner.token, 'POST', { content: '已结束留言' })).httpStatus, 409)
  })

  await t.test('cancellation needs other party and disputes remain available to administrators', async () => {
    const created = await call('/tasks', owner.token, 'POST', taskInput), id = created.task.id
    await call(`/tasks/${id}/accept`, helper.token, 'POST', {})
    assert.equal((await call(`/tasks/${id}/cancel`, owner.token, 'POST', {})).httpStatus, 409)
    assert.equal((await call(`/tasks/${id}/cancel-request`, helper.token, 'POST', { reason: '临时课程冲突' })).task.status, 'CANCEL_PENDING')
    assert.equal((await call(`/tasks/${id}/cancel-confirm`, helper.token, 'POST', { accepted: true })).httpStatus, 403)
    assert.equal((await call(`/tasks/${id}/cancel-confirm`, stranger.token, 'POST', { accepted: true })).httpStatus, 403)
    assert.equal((await call(`/tasks/${id}/cancel-confirm`, owner.token, 'POST', { accepted: false })).task.status, 'CANCEL_DISPUTED')
    assert.equal((await call(`/tasks/${id}`, stranger.token)).task.cancelReason, null)
    assert.ok((await call('/admin/cancellations', admin.token)).tasks.some(task => task.id === id))
    assert.equal((await call(`/admin/tasks/${id}/cancellation`, admin.token, 'POST', { cancelled: false, reason: '双方沟通后继续任务' })).status, 'ASSIGNED')
    await call(`/tasks/${id}/cancel-request`, owner.token, 'POST', { reason: '已经不需要帮助' })
    assert.equal((await call(`/tasks/${id}/cancel-confirm`, helper.token, 'POST', { accepted: true })).task.status, 'CANCELLED')
    const open = await call('/tasks', owner.token, 'POST', taskInput)
    assert.equal((await call(`/tasks/${open.task.id}/cancel`, owner.token, 'POST', {})).task.status, 'CANCELLED')
  })

  await t.test('forum posts/comments, reports and moderation persist with audit records', async () => {
    const created = await call('/posts', owner.token, 'POST', { content: '校园图书馆周末开放吗？' })
    assert.equal(created.httpStatus, 201); postId = created.post.id
    const comment = await call(`/posts/${postId}/comments`, helper.token, 'POST', { content: '早上八点开门。' })
    assert.equal(comment.httpStatus, 201)
    assert.equal((await call(`/posts/${postId}`, stranger.token)).post.id, postId)
    assert.equal((await call(`/posts/${postId}/comments`, stranger.token)).comments.length, 1)
    const report = await call('/reports', stranger.token, 'POST', { targetType: 'COMMENT', targetId: comment.comment.id, reason: '内容需要复核' })
    assert.equal(report.httpStatus, 201)
    assert.equal((await call(`/admin/content/COMMENT/${comment.comment.id}`, admin.token)).content.content, '早上八点开门。')
    assert.equal((await call(`/admin/content/COMMENT/${comment.comment.id}/hide`, admin.token, 'POST', { reason: '已核实需要下架' })).status, 'HIDDEN')
    assert.equal((await call(`/posts/${postId}/comments`, stranger.token)).comments.length, 0)
    assert.equal((await call(`/admin/reports/${report.id}/resolve`, admin.token, 'POST', { status: 'RESOLVED', resolution: '已下架并记录' })).status, 'RESOLVED')
    await call(`/admin/content/POST/${postId}/hide`, admin.token, 'POST', { reason: '测试下架流程' })
    assert.equal((await call(`/posts/${postId}`, stranger.token)).httpStatus, 404)
    assert.equal((await call(`/posts/${postId}/comments`, helper.token, 'POST', { content: '不能回复下架帖子' })).httpStatus, 404)
  })

  await t.test('hidden tasks cannot be found or accepted by outsiders; terminal history is preserved', async () => {
    const created = await call('/tasks', owner.token, 'POST', taskInput), id = created.task.id
    await call(`/admin/content/TASK/${id}/hide`, admin.token, 'POST', { reason: '任务内容不适宜' })
    assert.equal((await call(`/tasks/${id}`, stranger.token)).httpStatus, 404)
    assert.equal((await call(`/tasks/${id}/accept`, helper.token, 'POST', {})).httpStatus, 409)
    assert.equal((await call('/tasks', stranger.token)).tasks.some(task => task.id === id), false)
    await call(`/admin/content/TASK/${taskId}/hide`, admin.token, 'POST', { reason: '已完成任务下架测试' })
    assert.equal((await call(`/tasks/${taskId}`, owner.token)).task.status, 'COMPLETED')
  })

  await t.test('actual mini-program services persist tasks, comments and reports through HTTP into MySQL', async () => {
    const first = createMiniProgram({ apiBaseUrl: base, account: 'one', testAccount: true })
    const second = createMiniProgram({ apiBaseUrl: base, account: 'two', testAccount: true })
    const [firstUser, secondUser] = await Promise.all([first.app.ensureLogin(), second.app.ensureLogin()])
    assert.notEqual(firstUser.id, secondUser.id)
    const task = await first.tasks.create(taskInput)
    assert.equal((await second.tasks.get(task.id)).exactLocation, null)
    assert.equal((await second.tasks.action(task.id, 'accept')).status, 'ASSIGNED')
    assert.equal((await second.tasks.get(task.id)).exactLocation, taskInput.exactLocation)
    await second.tasks.sendMessage(task.id, '服务层联调留言')
    assert.equal((await first.tasks.messages(task.id))[0].content, '服务层联调留言')
    await second.tasks.action(task.id, 'complete')
    assert.equal((await first.tasks.action(task.id, 'confirm')).statusLabel, '已完成')
    const post = await first.forum.create('客户端联调文字帖')
    const comment = await second.forum.comment(post.id, '客户端联调评论')
    assert.equal((await first.forum.get(post.id)).commentCount, 1)
    const report = await first.reports.create('COMMENT', comment.id, '联调举报处理')
    assert.ok((await call('/admin/reports', admin.token)).reports.some(item => item.id === report.id))
    await call(`/admin/content/COMMENT/${comment.id}/hide`, admin.token, 'POST', { reason: '联调下架评论' })
    assert.equal((await first.forum.get(post.id)).commentCount, 0)
    const profile = first.page('./pages/profile/index/index.js')
    await profile.onShow()
    await profile.switchDemoUser()
    assert.equal(first.app.globalData.user.id, secondUser.id)
    const [saved] = await pool.execute('SELECT status FROM tasks WHERE id = ?', [task.id])
    assert.equal(saved[0].status, 'COMPLETED')
    const forumPage = first.page('./pages/forum/detail/index.js')
    forumPage.onLoad({ id: post.id })
    await forumPage.load()
    assert.ok(forumPage.data.post)
    await call(`/admin/content/POST/${post.id}/hide`, admin.token, 'POST', { reason: '检查下架后的客户端状态' })
    await forumPage.load()
    assert.equal(forumPage.data.post, null)
    assert.ok(forumPage.data.error)
    const mode = env.wechatLoginMode
    try {
      env.wechatLoginMode = 'wechat'
      assert.equal((await call('/auth/wechat-login', null, 'POST', { code: 'demo:must-be-rejected' })).httpStatus, 401)
    } finally { env.wechatLoginMode = mode }
  })

  await t.test('ban revokes existing sessions, login and all writes; audit and metrics available', async () => {
    const openTask = await call('/tasks', stranger.token, 'POST', taskInput)
    const activeTask = await call('/tasks', owner.token, 'POST', taskInput)
    await call(`/tasks/${activeTask.task.id}/accept`, stranger.token, 'POST', {})
    const result = await call(`/admin/users/${stranger.user.id}/status`, admin.token, 'PATCH', { status: 'BLOCKED', reason: '多次发布垃圾信息' })
    assert.equal(result.status, 'BLOCKED')
    assert.equal((await call(`/tasks/${openTask.task.id}`, stranger.token)).httpStatus, 403)
    assert.equal((await call(`/tasks/${openTask.task.id}`, owner.token)).httpStatus, 404)
    const hiddenOpenTask = await call(`/admin/content/TASK/${openTask.task.id}`, admin.token)
    assert.equal(hiddenOpenTask.content.status, 'CANCELLED')
    assert.equal(hiddenOpenTask.content.visibility, 'HIDDEN')
    const disputedTask = await call(`/tasks/${activeTask.task.id}`, owner.token)
    assert.equal(disputedTask.task.status, 'CANCEL_DISPUTED')
    assert.equal(disputedTask.task.visibility, 'HIDDEN')
    assert.ok((await call('/admin/cancellations', admin.token)).tasks.some(task => task.id === activeTask.task.id))
    assert.equal((await call(`/tasks/${activeTask.task.id}/confirm`, owner.token, 'POST', {})).httpStatus, 409)
    assert.equal((await call(`/admin/tasks/${activeTask.task.id}/cancellation`, admin.token, 'POST', { cancelled: false, reason: '尝试恢复封禁中的任务' })).httpStatus, 409)
    assert.equal((await call(`/admin/tasks/${activeTask.task.id}/cancellation`, admin.token, 'POST', { cancelled: true, reason: '参与者被封禁，终止任务' })).status, 'CANCELLED')
    assert.equal((await call('/posts', stranger.token, 'POST', { content: '尝试绕过封禁' })).httpStatus, 403)
    assert.equal((await call('/tasks', stranger.token, 'POST', taskInput)).httpStatus, 403)
    assert.equal((await call(`/tasks/${taskId}/accept`, stranger.token, 'POST', {})).httpStatus, 403)
    assert.equal((await call('/auth/wechat-login', null, 'POST', { code: 'demo:stranger' })).httpStatus, 403)
    assert.ok((await call('/admin/actions', admin.token)).actions.length >= 5)
    assert.ok((await call('/admin/summary', admin.token)).tasks.total >= 3)
  })
})
